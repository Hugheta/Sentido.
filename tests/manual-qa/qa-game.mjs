import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error' && !/autoplay|AudioContext|speech/i.test(m.text())) errors.push(m.text()); });
await page.goto('http://localhost:4180', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.screenshot({ path: '/tmp/g-menu.png' });
await page.getByRole('button', { name: /Entrar no escuro/i }).click();
await page.waitForTimeout(600);
await page.screenshot({ path: '/tmp/g-brief.png' });
await page.getByRole('button', { name: /Começar a fase/i }).click();
await page.waitForTimeout(700);
await page.screenshot({ path: '/tmp/g-start.png' });
await page.keyboard.press('Space');
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/g-scan.png' });
for (let i = 0; i < 2; i++) { await page.keyboard.press('ArrowUp'); await page.waitForTimeout(280); }
await page.keyboard.press('Space');
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/g-walk.png' });
await page.getByRole('button', { name: /Abrir pausa/i }).click();
await page.waitForTimeout(400);
await page.getByRole('button', { name: /Mapa de apoio/i }).click();
await page.waitForTimeout(300);
await page.screenshot({ path: '/tmp/g-pause.png' });
await page.getByRole('button', { name: /Continuar a fase/i }).click();
await page.waitForTimeout(300);
await page.keyboard.press('ArrowUp');
await page.waitForTimeout(400);
console.log('HEADING:', await page.locator('h1').first().innerText());
console.log('ERRORS:', errors);
await browser.close();
