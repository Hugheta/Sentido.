import { chromium } from 'playwright';
const browser = await chromium.launch();
const d = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
await d.goto('http://localhost:4182', { waitUntil: 'networkidle' });
await d.locator('#fases').scrollIntoViewIfNeeded();
await d.waitForTimeout(900);
await d.screenshot({ path: '/tmp/s-phases.png' });
await d.locator('#como-jogar').scrollIntoViewIfNeeded();
await d.waitForTimeout(700);
await d.screenshot({ path: '/tmp/s-how.png' });
const m = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
await m.goto('http://localhost:4182', { waitUntil: 'networkidle' });
await m.waitForTimeout(1200);
await m.screenshot({ path: '/tmp/s-m-hero.png' });
await m.getByRole('button', { name: /Entrar no escuro/i }).click();
await m.waitForTimeout(500);
await m.screenshot({ path: '/tmp/s-m-brief.png' });
await m.getByRole('button', { name: /Começar a fase/i }).click();
await m.waitForTimeout(600);
await m.keyboard.press('Space');
await m.waitForTimeout(500);
await m.screenshot({ path: '/tmp/s-m-game.png' });
await browser.close();
